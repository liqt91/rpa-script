// ── GUI 网页捕获跟随标签页切换：切标签/切窗口时把捕获模式重瞄到新的激活标签页 ──
chrome.tabs.onActivated.addListener(({ tabId }) => {
  const gc = agent.guiCapture;
  if (!gc || tabId === gc.tabId) return;
  const prevTabId = gc.tabId;
  gc.tabId = tabId;
  gc.prevTabId = prevTabId;
  gc.captureActive = false;
  // 退出旧标签页捕获模式（保留会话，不结束）
  chrome.tabs.sendMessage(prevTabId, { action: 'exitCaptureMode' }).catch(() => {});
  // 进入新标签页捕获模式（尽力而为；注入失败不结束会话，等下一次切换/载入完成）
  const enter = () => chrome.tabs.sendMessage(tabId, {
    action: 'launchBrowserCapture',
    payload: { requestId: gc.requestId, webOnly: gc.webOnly },
  });
  enter().then(() => { gc.captureActive = true; }).catch(async () => {
    try {
      await ensureContentScripts(tabId);
      await enter();
      gc.captureActive = true;
    } catch (e) {
      gc.captureActive = false;
      console.warn('[RPA] GUI 捕获重瞄失败 tab=', tabId, e);
    }
  });
});

// ── GUI 网页捕获：同标签页载入完成后自动进入捕获（载入中启动/切换到的场景） ──
chrome.tabs.onUpdated.addListener((tabId, changeInfo) => {
  if (changeInfo.status !== 'complete') return;
  const gc = agent.guiCapture;
  if (!gc || tabId !== gc.tabId || gc.captureActive) return;
  gc.captureActive = true;  // 防重入
  const enter = () => chrome.tabs.sendMessage(tabId, {
    action: 'launchBrowserCapture',
    payload: { requestId: gc.requestId, webOnly: gc.webOnly },
  });
  enter().catch(async () => {
    gc.captureActive = false;  // 失败允许后续重试
    try {
      await ensureContentScripts(tabId);
      await enter();
      gc.captureActive = true;
    } catch (e) {
      gc.captureActive = false;
      console.warn('[RPA] onUpdated 重试失败 tab=', tabId, e);
    }
  });
});

// ── Handle messages from content scripts and side panel ──

chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  // 0a) Content script 请求把当前标签页所在窗口置前台（输入前窗口前置）
  if (message.action === 'activateWindow') {
    const tab = sender.tab;
    if (!tab || tab.id == null) {
      sendResponse({ ok: false });
      return false;
    }
    (async () => {
      try {
        await chrome.tabs.update(tab.id, { active: true });
        await chrome.windows.update(tab.windowId, { focused: true });
        sendResponse({ ok: true });
      } catch (e) {
        sendResponse({ ok: false, error: e?.message || String(e) });
      }
    })();
    return true; // async
  }

  // 0) 选项页面请求立即重连（自动发现端口）
  if (message.action === 'reconnect') {
    (async () => {
      try {
        const host = message.host || DEFAULT_BACKEND_HOST;
        const port = message.port ? parseInt(message.port, 10) : 0;
        await chrome.storage.local.set({ backendHost: host });
        const wsUrl = port
          ? buildWsUrl(host, port)
          : await getBackendUrlWithDiscovery();
        if (port) await chrome.storage.local.set({ backendPort: String(port) });
        agent._connect(wsUrl);
        await new Promise(r => setTimeout(r, 1000));
        sendResponse({ connected: agent.ws?.readyState === WebSocket.OPEN });
      } catch (e) {
        sendResponse({ connected: false, error: e.message });
      }
    })();
    return true;
  }

  // 1) Side panel 请求最近一次捕获的数据
  if (message.action === 'getCapturePayload') {
    sendResponse({
      payload: agent.lastCapturePayload,
      tabId: agent.lastCaptureTabId,
    });
    return false;
  }

  // 1a) Side panel 选中候选方案 → 转发给捕获来源标签页
  if (message.action === 'selectCandidate') {
    const tabId = agent.lastCaptureTabId;
    if (!tabId) {
      sendResponse({ forwarded: false, error: 'no capture tab' });
      return false;
    }
    chrome.tabs.sendMessage(tabId, { action: 'selectCandidate', payload: message.payload }).catch(() => {});
    sendResponse({ forwarded: true });
    return false;
  }

  // 2) Side panel 请求校验元素 → 转发给对应标签页的 content_capture.js
  if (message.action === 'verifyElement') {
    console.log('[Agent] verifyElement received:', JSON.stringify(message).slice(0, 200));
    // sidepanel.js 的 send() 把参数包在 payload 里: { action, payload: { tabId, payload } }
    const tabId = message.tabId ?? message.payload?.tabId;
    const payload = message.payload?.payload ?? message.payload;
    console.log('[Agent] verifyElement: tabId=' + tabId + ' payloadKeys=' + Object.keys(payload || {}).join(','));
    if (!tabId) {
      console.log('[Agent] verifyElement: missing tabId');
      sendResponse({ error: 'tabId required' });
      return false;
    }
    ensureContentScripts(tabId)
      .then(() => {
        console.log('[Agent] verifyElement: forwarding to tab ' + tabId);
        return chrome.tabs.get(tabId).then(tab => {
          console.log('[Agent] verifyElement: tab URL = ' + (tab?.url || 'unknown'));
          return chrome.tabs.sendMessage(tabId, { action: 'verifyElement', payload });
        });
      })
      .then(result => {
        console.log('[Agent] verifyElement: tab responded', result);
        sendResponse(result);
      })
      .catch(err => {
        console.log('[Agent] verifyElement: error ' + err.message);
        sendResponse({ error: err.message });
      });
    return true; // async
  }

  // 2a) Side panel 请求重新计算循环锚点 → 转发给捕获标签页
  if (message.action === 'recomputeAnchor') {
    const tabId = message.tabId ?? message.payload?.tabId;
    const payload = message.payload?.payload ?? message.payload;
    if (!tabId) {
      sendResponse({ error: 'tabId required' });
      return false;
    }
    ensureContentScripts(tabId)
      .then(() => chrome.tabs.sendMessage(tabId, { action: 'recomputeAnchor', payload }))
      .then(result => sendResponse(result))
      .catch(err => sendResponse({ error: err.message }));
    return true;
  }

  // 2b) Side panel 请求校验相对选择器 → 转发给捕获标签页
  if (message.action === 'verifyRelative') {
    const tabId = message.tabId ?? message.payload?.tabId;
    const payload = message.payload?.payload ?? message.payload;
    if (!tabId) {
      sendResponse({ error: 'tabId required' });
      return false;
    }
    ensureContentScripts(tabId)
      .then(() => chrome.tabs.sendMessage(tabId, { action: 'verifyRelative', payload }))
      .then(result => sendResponse(result))
      .catch(err => sendResponse({ error: err.message }));
    return true;
  }

  // 2c) Side panel 请求根据已选锚点计算相对选择器 → 转发给捕获标签页
  if (message.action === 'computeRelativeFromAnchor') {
    const tabId = message.tabId ?? message.payload?.tabId;
    const payload = message.payload?.payload ?? message.payload;
    if (!tabId) {
      sendResponse({ error: 'tabId required' });
      return false;
    }
    ensureContentScripts(tabId)
      .then(() => chrome.tabs.sendMessage(tabId, { action: 'computeRelativeFromAnchor', payload }))
      .then(result => sendResponse(result))
      .catch(err => sendResponse({ error: err.message }));
    return true;
  }

  // 2d) Side panel 设置/清除“当前激活锚点”（锚点优先捕获）→ 转发给可见标签页
  if (message.action === 'setActiveAnchor') {
    const payload = message.payload?.payload ?? message.payload ?? {};
    const explicitTab = message.tabId ?? message.payload?.tabId;
    const forward = (tid) => {
      if (!tid) { sendResponse({ error: 'no active tab' }); return; }
      ensureContentScripts(tid)
        .then(() => chrome.tabs.sendMessage(tid, { action: 'setActiveAnchor', payload }))
        .then((result) => sendResponse(result))
        .catch((err) => sendResponse({ error: err.message }));
    };
    if (explicitTab) {
      forward(explicitTab);
    } else {
      chrome.tabs.query({ active: true, lastFocusedWindow: true })
        .then((tabs) => forward(tabs?.[0]?.id ?? agent.lastCaptureTabId))
        .catch(() => forward(agent.lastCaptureTabId));
    }
    return true;
  }

  // 3) Content script 返回校验结果 → 广播给 side panel
  if (message.action === 'verifyResult') {
    // Broadcast to side panel (and anyone listening)
    chrome.runtime.sendMessage({ action: 'verifyResultBroadcast', payload: message.payload })
      .catch(() => {});
    sendResponse({ forwarded: true });
    return false;
  }

  // 4) Content script 通知捕获完成 → 缓存数据并打开 side panel（不保存到后台）
  // content_capture.js → WS: GUI 原生捕获模式结果
  if (message.action === 'browserCaptureComplete') {
    agent.guiCapture = null;
    agent._send('browserCaptureComplete', message.payload);
    sendResponse({ ok: true });
    return false;
  }

  // 4a) Content script 通知 GUI 捕获取消（Esc）→ 转发 WS 让 overlay 退出
  if (message.action === 'browserCaptureCancelled') {
    agent.guiCapture = null;
    agent._send('browserCaptureComplete', {
      requestId: message.payload?.requestId,
      result: { error: '已取消', backToDesktop: !!message.payload?.backToDesktop },
    });
    sendResponse({ ok: true });
    return false;
  }

  // 4b) Content script 上报 GUI 捕获悬停元素信息 → 转发 WS，overlay 悬浮窗实时显示
  if (message.action === 'guiHoverInfo') {
    agent._send('guiHoverInfo', message.payload);
    sendResponse({ ok: true });
    return false;
  }

  if (message.action === 'captureElement') {
    agent.lastCapturePayload = message.payload;
    agent.lastCaptureTabId = sender.tab?.id || null;

    // Notify side panel to refresh (in case it's already open)
    chrome.runtime.sendMessage({ action: 'newCaptureAvailable' }).catch(() => {});

    // Open side panel on the capturing tab
    if (sender.tab?.id) {
      try {
        chrome.sidePanel.open({ tabId: sender.tab.id }).catch(() => {});
      } catch (_e) {}
    }
    sendResponse({ cached: true });
    return false;
  }

  // 5) Side panel 点击保存 → 转发到后端
  // 保存元素（通过 HTTP 同步等待后端结果）
  if (message.action === 'saveElement') {
    (async () => {
      try {
        const host = await getBackendHost();
        const port = await getBackendPort();
        const resp = await fetch(`http://${host}:${port}/api/extension/elements`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(message.payload),
        });
        const data = await resp.json();
        if (!resp.ok) {
          sendResponse({ saved: false, error: data?.detail || resp.statusText });
          return;
        }
        sendResponse({ saved: true, element: data });
      } catch (e) {
        sendResponse({ saved: false, error: e.message });
      }
    })();
    return true;
  }

  // 5a) Side panel 请求流程列表
  if (message.action === 'getWorkflows') {
    (async () => {
      try {
        const host = await getBackendHost();
        const port = await getBackendPort();
        const resp = await fetch(`http://${host}:${port}/api/extension/workflows`);
        const data = await resp.json();
        sendResponse({ workflows: data });
      } catch (e) {
        sendResponse({ error: e.message });
      }
    })();
    return true;
  }

  // 5b) Side panel 请求流程元素列表
  if (message.action === 'getWorkflowElements') {
    (async () => {
      try {
        const host = await getBackendHost();
        const port = await getBackendPort();
        const wfId = message.workflowId;
        const resp = await fetch(`http://${host}:${port}/api/extension/elements?workflow_id=${wfId}`);
        const data = await resp.json();
        sendResponse({ elements: data });
      } catch (e) {
        sendResponse({ error: e.message });
      }
    })();
    return true;
  }

  // 5c) Side panel 请求某个元素的有效选择器链（支持 child 作为锚点）
  if (message.action === 'getElementChain') {
    (async () => {
      try {
        const host = await getBackendHost();
        const port = await getBackendPort();
        const { workflowId, name } = message.payload || {};
        const resp = await fetch(`http://${host}:${port}/api/extension/elements/${encodeURIComponent(name)}/chain?workflow_id=${encodeURIComponent(workflowId)}`);
        const data = await resp.json();
        sendResponse(data);
      } catch (e) {
        sendResponse({ error: e.message });
      }
    })();
    return true;
  }

  // 5d) Side panel 请求单个元素完整数据（用于编辑现有元素）
  if (message.action === 'getElementByName') {
    (async () => {
      try {
        const host = await getBackendHost();
        const port = await getBackendPort();
        const { workflowId, name } = message.payload || {};
        console.log('[Background] getElementByName request:', { workflowId, name });
        const url = `http://${host}:${port}/api/extension/elements/${encodeURIComponent(name)}?workflow_id=${encodeURIComponent(workflowId)}`;
        const resp = await fetch(url);
        const data = await resp.json().catch(() => ({}));
        if (!resp.ok) {
          console.warn('[Background] getElementByName failed:', resp.status, url, data);
          sendResponse({ error: data?.detail || data?.error || `HTTP ${resp.status}` });
          return;
        }
        console.log('[Background] getElementByName response:', data);
        sendResponse(data);
      } catch (e) {
        console.warn('[Background] getElementByName error:', e);
        sendResponse({ error: e.message || String(e) });
      }
    })();
    return true;
  }

  // 6) Content script 查询当前捕获启用状态（页面刷新后同步）
  if (message.action === 'queryCaptureState') {
    sendResponse({ captureEnabled: agent.sidePanelOpen });
    return false;
  }

  if (message.action === 'captureScreenshot') {
    chrome.tabs.captureVisibleTab({ format: 'png' })
      .then(dataUrl => sendResponse({ dataUrl }))
      .catch(err => sendResponse({ error: err.message }));
    return true;
  }

  if (message.action === 'captureElementScreenshot') {
    const { rect, dpr = 1 } = message;
    const padding = 10 * dpr;

    chrome.tabs.captureVisibleTab({ format: 'png' })
      .then(async (dataUrl) => {
        try {
          const resp = await fetch(dataUrl);
          const blob = await resp.blob();
          const bitmap = await createImageBitmap(blob);

          const sx = Math.max(0, Math.round(rect.left * dpr - padding));
          const sy = Math.max(0, Math.round(rect.top * dpr - padding));
          const sw = Math.min(bitmap.width - sx, Math.round(rect.width * dpr + padding * 2));
          const sh = Math.min(bitmap.height - sy, Math.round(rect.height * dpr + padding * 2));

          const canvas = new OffscreenCanvas(sw, sh);
          const ctx = canvas.getContext('2d');
          ctx.drawImage(bitmap, sx, sy, sw, sh, 0, 0, sw, sh);

          const croppedBlob = await canvas.convertToBlob({ type: 'image/png' });
          const reader = new FileReader();
          reader.onloadend = () => sendResponse({ dataUrl: reader.result });
          reader.readAsDataURL(croppedBlob);
        } catch (err) {
          sendResponse({ error: err.message });
        }
      })
      .catch(err => sendResponse({ error: err.message }));
    return true;
  }

  if (message.action === 'notifyElementCaptured') {
    chrome.tabs.query({}, (tabs) => {
      tabs.forEach((tab) => {
        if (!tab.id) return;
        chrome.tabs.sendMessage(tab.id, { action: 'elementCaptured', payload: message.payload })
          .catch(() => {});
      });
    });
    sendResponse({ broadcast: true });
    return false;
  }

  // 7) 查询 WebSocket 连接状态
  if (message.action === 'getConnectionStatus') {
    sendResponse({ connected: agent.ws?.readyState === WebSocket.OPEN });
    return false;
  }

  return false;
});

// ── Side Panel 长连接生命周期（比 beforeunload 可靠）──
chrome.runtime.onConnect.addListener((port) => {
  if (port.name !== 'sidePanel') return;

  // side panel 打开
  agent.sidePanelOpen = true;
  const enabled = true;
  chrome.tabs.query({}, (tabs) => {
    tabs.forEach((tab) => {
      if (!tab.id) return;
      chrome.tabs.sendMessage(tab.id, { action: 'setCaptureEnabled', enabled })
        .catch(() => {});
    });
  });

  port.onDisconnect.addListener(() => {
    // side panel 关闭
    agent.sidePanelOpen = false;
    const enabled = false;
    chrome.tabs.query({}, (tabs) => {
      tabs.forEach((tab) => {
        if (!tab.id) return;
        chrome.tabs.sendMessage(tab.id, { action: 'setCaptureEnabled', enabled })
          .catch(() => {});
      });
    });
  });
});

// MV3 keep-alive: 闹钟触发时检查并重连 WS，防止 Service Worker 被浏览器暂停后断连
chrome.alarms.onAlarm.addListener(async (alarm) => {
  if (alarm.name === 'keepAlive') {
    console.log('[Agent] keepAlive alarm');
    if (!agent.ws || agent.ws.readyState !== WebSocket.OPEN) {
      console.log('[Agent] reconnecting from keepAlive alarm');
      const wsUrl = await getBackendUrlWithDiscovery();
      agent._connect(wsUrl);
    } else {
      // WS 正常，发送 ping 保持连接活跃
      agent._send('ping');
    }
  }
});
