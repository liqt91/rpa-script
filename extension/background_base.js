/**
 * RPA Script Browser Agent — Background Service Worker
 *
 * Architecture:
 *   Backend (FastAPI WS)  <--WebSocket-->  background.js  <--chrome.tabs.sendMessage-->  content.js  <--DOM-->  Page
 *   Side Panel  <--chrome.runtime.onMessage-->  background.js  <--chrome.tabs.sendMessage-->  content_capture.js
 */

const DEFAULT_BACKEND_HOST = 'localhost';
const DEFAULT_BACKEND_PORT = 8811;
// 后端随机端口范围（与后端 _pick_free_port 保持一致）：8100-8199
const PORT_DISCOVER_LO = 8100;
const PORT_DISCOVER_HI = 8199;
const PORT_DISCOVER_CHUNK = 25;

function buildWsUrl(host, port) {
  return `ws://${host}:${port}/api/extension/ws`;
}

async function probeBackendHealth(host, port, timeoutMs = 600) {
  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), timeoutMs);
    const r = await fetch(`http://${host}:${port}/health`, { signal: ctrl.signal, cache: 'no-store' });
    clearTimeout(t);
    return r.ok;
  } catch (e) {
    return false;
  }
}

/**
 * 自动发现后端端口：先试 storage 缓存的端口；不通则在 8100-8199 范围
 * 分块并发探测 /health，命中后写回 storage（后端随机端口自适配）。
 * @returns {Promise<number|null>}
 */
async function discoverBackendPort(host, preferred) {
  const candidates = [];
  if (preferred && preferred >= 1024) candidates.push(preferred);
  for (let p = PORT_DISCOVER_LO; p <= PORT_DISCOVER_HI; p++) candidates.push(p);
  for (let i = 0; i < candidates.length; i += PORT_DISCOVER_CHUNK) {
    const chunk = candidates.slice(i, i + PORT_DISCOVER_CHUNK);
    const results = await Promise.all(chunk.map(p => probeBackendHealth(host, p).then(ok => (ok ? p : 0))));
    const found = results.find(p => p > 0);
    if (found) {
      try {
        await chrome.storage.local.set({ backendHost: host, backendPort: String(found) });
      } catch (e) {}
      console.log('[Agent] backend discovered on port', found);
      return found;
    }
  }
  return null;
}

/** 连接地址：缓存端口优先（立即连），失败自动发现新端口。 */
async function getBackendUrlWithDiscovery() {
  const cfg = await chrome.storage.local.get(['backendHost', 'backendPort']);
  const host = cfg.backendHost || DEFAULT_BACKEND_HOST;
  const preferred = parseInt(cfg.backendPort || '0', 10);
  if (preferred && (await probeBackendHealth(host, preferred, 400))) {
    return buildWsUrl(host, preferred);
  }
  const port = await discoverBackendPort(host, preferred);
  if (port) return buildWsUrl(host, port);
  return buildWsUrl(host, preferred || DEFAULT_BACKEND_PORT);
}

async function getBackendUrl() {
  const cfg = await chrome.storage.local.get(['backendHost', 'backendPort']);
  const host = cfg.backendHost || DEFAULT_BACKEND_HOST;
  const port = parseInt(cfg.backendPort || DEFAULT_BACKEND_PORT, 10);
  return buildWsUrl(host, port);
}

async function getBackendHost() {
  const cfg = await chrome.storage.local.get(['backendHost']);
  return cfg.backendHost || DEFAULT_BACKEND_HOST;
}

async function getBackendPort() {
  const cfg = await chrome.storage.local.get(['backendPort']);
  return parseInt(cfg.backendPort || DEFAULT_BACKEND_PORT, 10);
}

/**
 * Ensure the target tab has our content scripts injected.
 * Manifest-declared content scripts only auto-inject on navigation; tabs that
 * were already open (or that navigated before the extension loaded) need an
 * explicit injection before we can send them messages.
 */
async function ensureContentScripts(tabId) {
  try {
    await chrome.scripting.executeScript({
      target: { tabId },
      files: ['content.js', 'finder.js', 'content_capture.js'],
    });
  } catch (e) {
    console.warn('[Agent] ensureContentScripts failed for tab', tabId, e.message);
    throw e;
  }
}

// ── Background handler registry ──────────────────────────────
// Each extension/background_handlers/*.js calls registerBackgroundHandler()
// to self-register. background.js dispatches by type, no hardcoded type names.

const _backgroundHandlers = {};

function registerBackgroundHandler(type, fn) {
  _backgroundHandlers[type] = fn;
}

/**
 * 按 URL 片段在窗口中查找标签页，找不到时带重试。
 *
 * 解决 navigate 之后 tab.url 在 chrome.tabs 中提交存在时序延迟、
 * 导致 switchTab/closeTab 偶发匹配失败的问题：查询一次可能正落在
 * 「URL 已跳转但 tabs API 尚未更新」的瞬间，重试几次即可等到提交完成。
 */
async function findTabByUrlPattern(windowId, pattern, attempts = 4) {
  const p = String(pattern || '').toLowerCase();
  for (let i = 0; i < attempts; i++) {
    const tabs = await chrome.tabs.query({ windowId });
    const tab = tabs.find(t => t.url && t.url.toLowerCase().includes(p));
    if (tab) return tab;
    if (i < attempts - 1) await new Promise(r => setTimeout(r, 250));
  }
  return null;
}

// ─── Background handlers (generated by build_background_js.py) ───

class AgentBackground {
  constructor() {
    this.ws = null;
    this.reconnectTimer = null;
    this.pingTimer = null;
    this.clientId = null;
    this.pendingSteps = new Map(); // stepId -> {resolve, reject, timer}
    this.workTabId = null;
      this._lastTabUrl = null;         this._lastTabUrl = null;   // 工作流专用标签页 ID
    this.workWindowId = null;      // 工作流专用窗口 ID
    this.lastCapturePayload = null; // 最近一次捕获的元素数据（供 side panel 获取）
    this.lastCaptureTabId = null;   // 捕获来源标签页
    this.isRunning = false;         // 工作流运行中标志
    this.sidePanelOpen = false;     // side panel 是否打开
    this.guiCapture = null;         // GUI 网页捕获会话 { requestId, tabId, prevTabId, webOnly }
  }

  async start() {
    // 恢复工作窗口状态：MV3 service worker 会在空闲后休眠/重启，内存中的
    // workWindowId/workTabId 会丢失，导致步骤间"工作窗口已失效"。持久化到
    // chrome.storage.local，重启后在此恢复。
    try {
      const saved = await chrome.storage.local.get('rpaWorkState');
      const s = saved.rpaWorkState;
      if (s && s.workWindowId) {
        this.workWindowId = s.workWindowId;
        this.workTabId = s.workTabId || null;
        console.log('[Agent] restored work state:', this.workWindowId, this.workTabId);
      }
    } catch (_) {}

    const wsUrl = await getBackendUrlWithDiscovery();
    this._connect(wsUrl);

    // 点击扩展图标自动打开原生 Side Panel
    try {
      await chrome.sidePanel.setPanelBehavior({ openPanelOnActionClick: true });
    } catch (e) {
      console.warn('[Agent] sidePanel behavior not supported:', e.message);
    }

    // MV3 Service Worker keep-alive: 周期性闹钟防止浏览器暂停 Service Worker
    try {
      await chrome.alarms.create('keepAlive', { periodInMinutes: 0.5 });
    } catch (e) {
      console.warn('[Agent] alarms not supported:', e.message);
    }
  }

  _connect(wsUrl) {
    // 如果已有连接且目标 URL 相同，跳过
    if (this.ws?.url === wsUrl && (this.ws?.readyState === WebSocket.OPEN || this.ws?.readyState === WebSocket.CONNECTING)) {
      return;
    }

    // 如果已有连接但目标不同，强制关闭旧连接（切换后端端口）
    if (this.ws) {
      console.log('[Agent] Switching backend from', this.ws.url, 'to', wsUrl);
      try { this.ws.close(); } catch (e) {}
      this.ws = null;
    }

    // 清除旧的重连定时器，防止多个定时器同时触发
    if (this.reconnectTimer) {
      clearTimeout(this.reconnectTimer);
      this.reconnectTimer = null;
    }

    console.log('[Agent] Connecting to', wsUrl);
    this.ws = new WebSocket(wsUrl);

    this.ws.onopen = () => {
      console.log('[Agent] WS connected');
      const manifest = chrome.runtime.getManifest();
      this._send('register', {
        browser: this._detectBrowser(),
        version: manifest.version,
        extensionId: chrome.runtime.id || '',
        installType: 'development',
      });
      this._startPing();
    };

    this.ws.onmessage = (event) => {
      try {
        const msg = JSON.parse(event.data);
        this._onBackendMessage(msg);
      } catch (e) {
        console.error('[Agent] Invalid JSON from backend:', e);
      }
    };

    this.ws.onclose = () => {
      console.log('[Agent] WS closed, reconnecting with port discovery in 3s...');
      this._stopPing();
      this.reconnectTimer = setTimeout(async () => {
        const url = await getBackendUrlWithDiscovery();
        this._connect(url);
      }, 3000);
    };

    this.ws.onerror = (err) => {
      console.error('[Agent] WS error:', err);
    };
  }

  _detectBrowser() {
    const ua = navigator.userAgent;
    if (ua.includes('Edg/')) return 'edge';
    if (ua.includes('Chrome/')) return 'chrome';
    return 'unknown';
  }

  _send(action, payload = {}) {
    if (this.ws?.readyState === WebSocket.OPEN) {
      this.ws.send(JSON.stringify({ action, payload }));
    }
  }

  _startPing() {
    this.pingTimer = setInterval(() => {
      this._send('ping');
    }, 15000);
  }

  _stopPing() {
    if (this.pingTimer) {
      clearInterval(this.pingTimer);
      this.pingTimer = null;
    }
  }

  /**
   * Handle messages from backend.
   * Expected actions:
   *   - executeStep: { stepId, type, locator, selectorFamily, action, extra }
   */
  async _onBackendMessage(msg) {
    const { action, payload } = msg;
    console.log('[Agent] onBackendMessage:', action, JSON.stringify(payload).slice(0, 100));

    if (action === 'pong') return;

    if (action === 'executeStep') {
      await this._handleExecuteStep(payload);
      return;
    }

    if (action === 'runStarted') {
      this.isRunning = true;
      // Reset work window/tab references so navigate opens a fresh tab/window.
      // Do NOT close the actual browser window — if it's the only window,
      // removing it kills the browser process and breaks the extension connection.
      this.workWindowId = null;
      this.workTabId = null;
      this._lastTabUrl = null;
      await this._clearWorkState();
      console.log('[Agent] work window/tab reset for new run');
      return;
    }

    // GUI → Extension: 激活原生捕获模式
    if (action === 'launchBrowserCapture') {
      const { requestId } = payload || {};
      try {
        const tabs = await chrome.tabs.query({ active: true, currentWindow: true });
        const tab = tabs[0];
        if (!tab) {
          this.guiCapture = null;
          this._send('browserCaptureComplete', { requestId, result: { error: '没有活动标签页' } });
          return;
        }
        // 记录 GUI 捕获会话（用于标签页切换时跟随重瞄）
        this.guiCapture = { requestId, tabId: tab.id, prevTabId: null, webOnly: !!payload?.webOnly, captureActive: false };
        await ensureContentScripts(tab.id);
        await new Promise(r => setTimeout(r, 300));  // 等脚本初始化
        // 重试 3 次
        for (let i = 0; i < 3; i++) {
          try {
            await chrome.tabs.sendMessage(tab.id, {
              action: 'launchBrowserCapture',
              payload: { requestId, webOnly: !!payload?.webOnly },
            });
            this.guiCapture.captureActive = true;
            break;  // 成功
          } catch (e) {
            if (i === 2) throw e;
            await new Promise(r => setTimeout(r, 300));
          }
        }
        // 等待 content script 通过 WS 发送结果
        // content_capture.js 会在捕获完成后通过 chrome.runtime.sendMessage
        // 发送 browserCaptureComplete 回来
      } catch (e) {
        // 启动页为受限页面（edge:// 等）或载入中：不结束会话，
        // 等用户切到普通网页（tabs.onActivated）或载入完成（tabs.onUpdated）后自动进入
        if (this.guiCapture) this.guiCapture.captureActive = false;
        this._send('browserCaptureNote', { requestId, note: '当前页面无法捕获（受限页面），请切换到普通网页' });
      }
      return;
    }

    // GUI → Extension: 退出浏览器捕获模式（超时/失败/取消时）
    if (action === 'exitBrowserCapture') {
      const gc = this.guiCapture;
      this.guiCapture = null;
      const targetIds = new Set();
      if (gc?.tabId != null) targetIds.add(gc.tabId);
      if (gc?.prevTabId != null) targetIds.add(gc.prevTabId);
      try {
        const tabs = await chrome.tabs.query({ active: true, currentWindow: true });
        if (tabs[0]?.id != null) targetIds.add(tabs[0].id);
      } catch (e) {}
      // 向跟踪的捕获标签页（而非仅当前激活页）发退出，避免受限页/跨窗口时框选残留
      targetIds.forEach((tid) => chrome.tabs.sendMessage(tid, { action: 'exitCaptureMode' }).catch(() => {}));
      this._send('browserCaptureComplete', { requestId: payload?.requestId || '', result: { error: '已取消' } });
      return;
    }

    // GUI → Extension: 验证选择器 (只查物理可见页面: 非最小化窗口的 active tab)
    if (action === 'verifySelector') {
      const { requestId, selector } = payload || {};
      try {
        const wins = await chrome.windows.getAll({ populate: true });
        // 1. 过滤物理可见窗口（最小化 = 内容不在屏幕上）
        const visibleWins = wins.filter(w => w.state !== 'minimized');
        const focused = wins.find(w => w.focused) || null;
        // 2. 取每个可见窗口的 active tab（同窗口内只有 active tab 在屏幕上展示）
        let candidates = [];
        for (const w of visibleWins) {
          let tabs = [];
          try { tabs = await chrome.tabs.query({ windowId: w.id, active: true }); } catch (_) { continue; }
          const tab = tabs[0];
          if (!tab || tab.id == null || tab.discarded) continue;  // discarded = 内容已卸载，跳过
          candidates.push(tab);
        }
        // 3. 过滤编辑器/扩展/chrome 内部页（编辑器 SPA 按路径识别，端口已随机）
        candidates = candidates.filter(t =>
          t.url && /^https?:/i.test(t.url) &&
          !/workflow-editor\//i.test(t.url) &&
          !/chrome-extension:|chrome:|edge:|devtools:/i.test(t.url)
        );
        if (!candidates.length) {
          this._send('verifySelectorResult', { requestId, result: { found: false, count: 0, visible: 0, invisible: 0, error: '没有可见的网页标签页(请打开并展示目标页面)' } });
          return;
        }
        // 4. 排序: focused 窗口优先, 其余按 lastAccessed 降序（最近看的优先）
        candidates.sort((a, b) => {
          const af = focused && a.windowId === focused.id ? 0 : 1;
          const bf = focused && b.windowId === focused.id ? 0 : 1;
          if (af !== bf) return af - bf;
          return (b.lastAccessed || 0) - (a.lastAccessed || 0);
        });
        // 5. 逐个验证, 首个可见命中即返回
        const scanned = [];
        for (const tab of candidates) {
          let resp = null;
          try {
            await ensureContentScripts(tab.id);
            resp = await chrome.tabs.sendMessage(tab.id, {
              action: 'verifySelector',
              payload: { requestId, selector },
            });
          } catch (e) {
            resp = null;  // 注入/页面异常, 跳过继续
          }
          if (resp && resp.visible > 0) {
            // 提示: 打开多个相同页面时, 仅验证命中匹配到的这一个
            const sameUrlCount = candidates.filter(t => t.url === tab.url).length;
            this._send('verifySelectorResult', {
              requestId,
              result: {
                found: true, count: resp.count || 0, visible: resp.visible || 0, invisible: resp.invisible || 0,
                tabUrl: tab.url, tabTitle: tab.title || '',
                sameUrlCount,
              },
            });
            return;
          }
          scanned.push({
            tabUrl: tab.url, tabTitle: tab.title || '',
            count: resp?.count || 0, visible: resp?.visible || 0, invisible: resp?.invisible || 0,
          });
        }
        this._send('verifySelectorResult', {
          requestId,
          result: { found: false, count: 0, visible: 0, invisible: 0, scanned },
        });
      } catch (e) {
        this._send('verifySelectorResult', { requestId, result: { error: e?.message || String(e) } });
      }
      return;
    }

    // GUI → Extension: 拾取浏览器 DOM 元素
    if (action === 'browserPickElement') {
      const { x, y, requestId } = payload || {};
      try {
        const tabs = await chrome.tabs.query({ active: true, currentWindow: true });
        const tab = tabs[0];
        if (!tab) {
          this._send('browserPickResult', { requestId, result: { error: '没有活动标签页' } });
          return;
        }
        const resp = await chrome.tabs.sendMessage(tab.id, {
          action: 'browserPickElement',
          payload: { x, y, requestId },
        });
        this._send('browserPickResult', { requestId, result: resp?.result || resp || { error: '无响应' } });
      } catch (e) {
        this._send('browserPickResult', { requestId, result: { error: e?.message || String(e) } });
      }
      return;
    }

    console.log('[Agent] Unknown backend action:', action);
  }

  _isRestrictedUrl(url) {
    if (!url) return true;
    // newtab / blank are safe automation targets (browser default start pages)
    if (url === 'about:blank' || url.includes('newtab')) return false;
    const restricted = ['chrome://', 'edge://', 'chrome-extension://', 'about:', 'file://', 'data:', 'javascript:'];
    return restricted.some(p => url.startsWith(p));
  }

  // ── 工作窗口状态持久化（MV3 service worker 休眠不丢） ──
  async _persistWorkState() {
    try {
      await chrome.storage.local.set({
        rpaWorkState: { workWindowId: this.workWindowId, workTabId: this.workTabId },
      });
    } catch (_) {}
  }

  async _clearWorkState() {
    try { await chrome.storage.local.remove('rpaWorkState'); } catch (_) {}
  }

  async _ensureWorkTab(step) {
    const explicitWindowId = step.extra?.windowId ? Number(step.extra.windowId) : null;
    const explicitTabId = step.extra?.tabId ? Number(step.extra.tabId) : null;

    if (explicitTabId) {
      try {
        const tab = await chrome.tabs.get(explicitTabId);
        if (tab && !this._isRestrictedUrl(tab.url)) {
          return explicitTabId;
        }
      } catch (e) {
        throw new Error('指定的标签页已失效');
      }
    }

    if (explicitWindowId) {
      try {
        const win = await chrome.windows.get(explicitWindowId, { populate: true });
        if (win && win.tabs) {
          const usable = win.tabs.find(t => !this._isRestrictedUrl(t.url));
          if (usable) return usable.id;
        }
      } catch (e) {}
      throw new Error('指定的窗口中没有可用标签页');
    }

    if (this.workWindowId) {
      try {
        const win = await chrome.windows.get(this.workWindowId);
        if (!win) {
          throw new Error('工作窗口已被关闭，请先执行打开浏览器指令');
        }
        if (this.workTabId) {
          try {
            const tab = await chrome.tabs.get(this.workTabId);
            if (tab && !this._isRestrictedUrl(tab.url)) {
              return this.workTabId;
            }
          } catch (e) {
            throw new Error('工作标签页已被手动关闭，请先执行打开浏览器指令');
          }
        }
        throw new Error('工作标签页已失效，请先执行打开浏览器指令');
      } catch (e) {
        if (e.message.includes('工作') || e.message.includes('指定')) throw e;
        throw new Error('工作窗口已失效，请先执行打开浏览器指令');
      }
    }

    throw new Error('未找到工作窗口，请先执行打开浏览器或导航步骤');
  }

  async _injectContentScript(tabId) {
    try {
      await chrome.scripting.executeScript({
        target: { tabId },
        files: ['content.js'],
      });
      console.log('[Agent] content.js injected into tab', tabId);
    } catch (e) {
      console.warn('[Agent] content.js injection failed:', e.message);
      throw e;
    }
  }

  async _executeStepOnTab(tabId, step) {
    // sendMessage 在 content script 存在但不回调 sendResponse 时永不 settle（既不 resolve 也不 reject），
    // 会导致后端 exec 永久挂起。加超时保护，超时明确报错而非挂死。
    const timeoutMs = 15000;
    let timer;
    const timeout = new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(
        `目标标签页 content script 无响应（${timeoutMs / 1000}s），请刷新该页面或重载扩展后重试`
      )), timeoutMs);
    });
    try {
      return await Promise.race([
        chrome.tabs.sendMessage(tabId, { action: 'executeStep', step }),
        timeout,
      ]);
    } finally {
      clearTimeout(timer);
    }
  }

  async _handleExecuteStep(step) {
    const { stepId, type } = step;

    // ── Background handler dispatch (new system) ──
    const bgHandler = _backgroundHandlers[type];
    console.log('[Agent] _handleExecuteStep type=' + type + ' handlers=' + JSON.stringify(Object.keys(_backgroundHandlers)));
    if (bgHandler) {
      console.log('[Agent] dispatching to bg handler: ' + type);
      try {
        const result = await bgHandler(step, this);
        this._send('stepResult', { stepId, result });
      } catch (e) {
        this._send('stepError', { stepId, error: e.message });
      }
      return;
    }

    try {
      // Ensure we have a valid work tab (creates new one for navigate if needed)
      const tabId = await this._ensureWorkTab(step);

      // 操作前把目标窗口置前（best-effort）：真实鼠标/键盘操作必须窗口在前台才有效，
      // 也避免与用户当前所在窗口冲突。
      try {
        const workTab = await chrome.tabs.get(tabId);
        if (workTab?.windowId) {
          await chrome.windows.update(workTab.windowId, { focused: true });
        }
      } catch (_) {}

      // 向页面注入运行提示
      if (tabId) {
        chrome.tabs.sendMessage(tabId, { action: 'setRunningBanner', visible: true, stepType: type })
          .catch(() => {});
      }

      // Detect navigation caused by previous step BEFORE executing this one
      try {
        const prevTab = await chrome.tabs.get(tabId);
        if (this._lastTabUrl && prevTab.url !== this._lastTabUrl) {
          console.log('[Agent] tab navigated: ' + this._lastTabUrl + ' -> ' + prevTab.url);
          if (prevTab.status !== 'complete') {
            await new Promise((resolve) => {
              const listener = (tid, info) => {
                if (tid === tabId && info.status === 'complete') {
                  chrome.tabs.onUpdated.removeListener(listener);
                  resolve();
                }
              };
              chrome.tabs.onUpdated.addListener(listener);
              setTimeout(() => { chrome.tabs.onUpdated.removeListener(listener); resolve(); }, 5000);
            });
          }
          await this._injectContentScript(tabId);
          await new Promise(r => setTimeout(r, 500));
        }
        this._lastTabUrl = prevTab.url;
      } catch (_) {}

      // Try sending directly; if content script is missing, inject and retry once
      let result;
      try {
        result = await this._executeStepOnTab(tabId, step);
      } catch (sendErr) {
        const msg = sendErr?.message || '';
        const isMissing = msg.includes('Receiving end does not exist') || msg.includes('Could not establish connection');
        const isClosed = msg.includes('message channel') || msg.includes('back/forward cache');
        if (isMissing || isClosed) {
          console.log('[Agent] content script missing/closed (bfcache?), re-injecting...');
          await this._injectContentScript(tabId);
          await new Promise(r => setTimeout(r, 1500));
          result = await this._executeStepOnTab(tabId, step);
        } else {
          throw sendErr;
        }
      }

      if (result?.status === 'success') {
        // Enrich with screen coordinates if not already calibrated
        if (result?.result?.viewX !== undefined && result?.result?.screenX === undefined) {
          try {
            const tab = await chrome.tabs.get(tabId);
            if (tab) {
              const win = await chrome.windows.get(tab.windowId);
              const dpr = result.result.dpr || 1;
              const leftChrome = Math.round((win.width - tab.width) / 2);
              const topChrome = win.height - tab.height;
              const screenX = Math.round((win.left + leftChrome + result.result.viewX) * dpr);
              const screenY = Math.round((win.top + topChrome + result.result.viewY) * dpr);
              result.result.screenX = screenX;
              result.result.screenY = screenY;
            }
          } catch (_) {}
        }
        this._send('stepResult', { stepId, result: result.result });
      } else {
        this._send('stepError', { stepId, error: result?.error || 'Unknown content error' });
      }
    } catch (err) {
      console.error('[Agent] executeStep failed:', err);
      this._send('stepError', { stepId, error: err.message });
    }
  }
}

